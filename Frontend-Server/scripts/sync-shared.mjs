// Copies code shared with the Angular app into src/shared/, so both run exactly the
// same implementation. The copies are gitignored and regenerated before every
// build, test and dev run - edit the originals in Frontend/, never the copies.
//
// Why a copy and not an import: tsconfig pins rootDir to src/ and runs strict,
// the Angular sources are neither inside it nor strict clean. The copy is
// therefore marked @ts-nocheck; it is typed at the boundary where we use it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** [source relative to the package root, target relative to the package root] */
const SHARED_FILES = [
    ['../Frontend/projects/edu-sharing-ui/src/lib/util/VCard.ts', 'src/shared/VCard.ts'],
    ['../Frontend/projects/edu-sharing-ui/src/lib/util/license-url.ts', 'src/shared/license-url.ts'],
];

for (const [from, to] of SHARED_FILES) {
    const source = path.resolve(root, from);
    const target = path.resolve(root, to);
    const content = fs.readFileSync(source, 'utf8');
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, `// @ts-nocheck\n// GENERATED by scripts/sync-shared.mjs from ${from} - do not edit\n${content}`);
}
