// Generates TypeScript types for the REST models this server reads, from the same
// openapi.json the Angular client (ngx-edu-sharing-api) is generated from. Types
// only - nothing of it exists at runtime.
//
// The spec has well over a thousand schemas; only those reachable from ROOT_SCHEMAS
// are kept, so the output stays small and a change elsewhere in the API does not
// touch this server. Add a root here when the server starts reading another model.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** same relative location as in the repository - the Dockerfile mirrors it */
const SPEC = path.resolve(root, '../Backend/services/rest/api/src/main/resources/openapi.json');
const TARGET = path.resolve(root, 'src/shared/api-types.ts');

// node metadata (node-metadata.ts), the config response (config-cache.ts) and the
// contexts with their translation overrides (translation-overrides.ts)
const ROOT_SCHEMAS = ['NodeEntry', 'NodeVersionEntry', 'Config', 'Context'];

const REF_PREFIX = '#/components/schemas/';

const spec = JSON.parse(fs.readFileSync(SPEC, 'utf8'));
const schemas = spec.components.schemas;

/** every schema transitively referenced from the roots */
function reachable(names) {
    const seen = new Set();
    const pending = [...names];
    while (pending.length > 0) {
        const name = pending.pop();
        if (seen.has(name)) {
            continue;
        }
        if (schemas[name] === undefined) {
            throw new Error(`schema ${name} not found in ${SPEC}`);
        }
        seen.add(name);
        JSON.stringify(schemas[name], (key, value) => {
            if (key === '$ref' && typeof value === 'string' && value.startsWith(REF_PREFIX)) {
                pending.push(value.slice(REF_PREFIX.length));
            }
            return value;
        });
    }
    return [...seen].sort();
}

const kept = reachable(ROOT_SCHEMAS);
const reduced = {
    openapi: spec.openapi,
    info: spec.info,
    paths: {},
    components: { schemas: Object.fromEntries(kept.map((name) => [name, schemas[name]])) },
};

const ast = await openapiTS(reduced);
fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(
    TARGET,
    `// GENERATED by scripts/generate-api-types.mjs from ${path.relative(root, SPEC)} - do not edit\n` +
        `// schemas: ${kept.join(', ')}\n` +
        astToString(ast),
);
